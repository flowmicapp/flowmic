// 🔴 THE FIFTEEN SHARDS, LISTED ONCE — and the reason it is a list and not a
// generated table. Each shard's `*_STRINGS` is a VIEW of the generated
// catalogue sliced by that shard's own key contract, so this array is what
// keeps every shard file wired into production: a shard that stops being
// listed here stops contributing keys to `S`, and the parity/coverage numbers
// say so immediately. Written as data rather than as fifteen spreads per
// locale because the per-locale dimension is exactly what this migration
// removed — the old form was 15 × 4 spread lines and would have been 15 × 9.
const SHARD_VIEWS = [
  NAV_STRINGS,
  DEVICES_STRINGS,
  CLOUD_STRINGS,
  PAIRING_STRINGS,
  SETTINGS_STRINGS,
  TIMELINE_STRINGS,
  SEARCH_STRINGS,
  CAPSULE_STRINGS,
  CONNECTION_STRINGS,
  SIDECAR_STRINGS,
  PROBE_STRINGS,
  PORTABLE_STRINGS,
  STATS_STRINGS,
  DISCLOSURE_STRINGS,
  UPDATE_STRINGS,
] as const;

export type { StringKey };

/** Guard/test surface: the full per-locale merged catalogues. */
export const S_BY_LOCALE = Object.fromEntries(
  UI_LOCALES.map((l) => [
    l,
    Object.assign({}, ...SHARD_VIEWS.map((shard) => shard[l])) as Record<StringKey, string>,
  ]),
) as Record<UiLocale, Record<StringKey, string>>;

export const S: Record<StringKey, string> = reactive({ ...S_BY_LOCALE[getLocale()] });

onLocaleChange((l) => {
  Object.assign(S, S_BY_LOCALE[l]);
  // <html lang> follows the EXPLICIT choice only (affects font/IME heuristics);
  // it is set again at hydrate — it never comes from the OS either.
  if (typeof document !== 'undefined') document.documentElement.lang = l;
});

