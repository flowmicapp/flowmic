// V2-07.8a UI string catalogue — now with the locale axis the old header
// promised as「a later 偏好 card」("a later preference card"). This IS that card.
//
// Red-line clarification (docs/decisions/2026-07-28-i18n-four-locales-and-theme.md):
// 「UI 不跟随 OS locale」("UI does not follow OS locale") has not been
// overturned — what it forbids is「从系统 locale 推断」("inferring from the
// system locale"), not multiple languages. The UI language recognizes only
// two things: the user's explicit choice (setLocale), or the choice
// persisted in storage (hydrateLocale). Both live in ./strings/locale.ts;
// this file never touches the OS.
//
// Mechanism (why not one of the hundreds of `S.foo` call sites needs to change):
//   ① Each shard went from 「a single zh constant」to 「a per-locale table
//      per key」({ 'zh-CN': {...}, en: {...}, ja: {...}, ko: {...} } as
//      const — four locales as of V2-07.8b; Record<UiLocale, …>
//      compile-time-forces every shard to hand over all four);
//   ② This file merges the ten shards by locale into S_BY_LOCALE, then turns
//      S into a **reactive object**, initialized to the current locale's copy;
//   ③ setLocale() changes the ref in locale.ts → the onLocaleChange
//      subscription here does Object.assign(S, S_BY_LOCALE[new locale]) to
//      swap the whole value in place;
//   ④ `S.foo` in templates reads a reactive property at render time; Vue's
//      dependency tracking makes every component that uses it re-render on
//      its own — no restart, no refresh, call sites untouched.
//   The derived tables (MODE_BADGE / TL_BATCH_MSG / SIDECAR_LABEL /
//   INJECT_FAIL_REASON) work the same way: they stay in their original
//   shard, read getLocale() (a ref) via a getter/function, and get tracked
//   the moment they're called during render. Circular imports are avoided by
//   the one-directional edge "shard → locale.ts leaf" (the circular-import
//   lint runs Tarjan across the whole repo — no cycles).
//
// 🔴 Correction (2026-08-14, nine-locale migration) — of the ① above, only
// half is still true; the original text is kept because ②③④ haven't changed
// a single character, and those three are what makes "call sites don't need
// to change" hold.
//   · Shards **no longer hold a per-locale table**: each now declares
//     **which keys this shard has** (`export const NAV_KEYS = [...]`, with
//     each key's rationale comment still sitting next to it); the
//     translations live in `i18n/desktop/<code>.json`, and the merged table
//     is generated by `scripts/i18n/gen-desktop-ts.mjs` into
//     `./strings/generated/catalogue.g.ts`.
//   · The guard "`Record<UiLocale, …>` compile-time-forces every shard to
//     hand over all four" **is gone**; what replaced it is owner's
//     2026-08-14 ruling to fall missing translations back to English (book
//     17, §0-bis): the generator emits each language as
//     `{ ...EN, …whatever it has translated… }` ⇒ a missing translation is
//     structurally guaranteed to be English, never an empty string or a bare
//     key; **the cost is that we now have to know for ourselves how much is
//     missing** ⇒ `i18n/desktop/coverage.json` is how that half gets paid
//     off, and `i18n-generated-fresh` is its gate.
//   · Adding a tenth language now **touches neither this file nor any single
//     shard**: add a line to the registry + a data file + run the generator
//     once (docs/strategy/2026-08-14-locale-expansion-architecture.md §2).
//
// Guard: S_BY_LOCALE is the guard/test surface — locale-parity.test.ts
// asserts that every locale's key set exactly matches the baseline locale's,
// printing any missing keys by name.
// Note ./strings/ deliberately has no index.ts — with moduleResolution:Bundler
// a bare './strings' always resolves to THIS file.

